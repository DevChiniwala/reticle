// Emit dist/desktop-contract.cjs from the canonical TypeScript constants in src/desktop-contract.ts.
//
// An Electron preload is CommonJS — a sandboxed one cannot load an ESM build at all — so it cannot
// import the contract it has to agree with. Before this generator, the values were hand-copied into
// six files and a rename in any one broke desktop silently while every test still passed.
//
// Generating removes the copy rather than policing it: the CJS side receives exactly the values the
// ESM side exports, and a drift test can assert the two are identical instead of hoping.
//
// `renderDesktopContract` is a pure function over its input so the parity test can call it with the
// constants straight from src (no dist needed). The CLI entry feeds it the built dist and writes.

/** Render the CommonJS module text for a `name → value` record. */
export function renderDesktopContract(contract) {
  const lines = Object.entries(contract).map(
    ([name, value]) => `exports.${name} = ${JSON.stringify(value)};`,
  );
  return [
    '// GENERATED by scripts/gen-desktop-contract.mjs — do not edit.',
    '//',
    '// The CommonJS view of the desktop wiring contract, for an Electron preload/main process that',
    '// cannot import the ESM build. Edit src/desktop-contract.ts and rebuild @reticlehq/core.',
    "'use strict';",
    ...lines,
    'Object.freeze(exports);',
    '',
  ].join('\n');
}

/** Render the CJS type declaration (.d.cts) for a `name → value` record. */
export function renderDesktopContractDts(contract) {
  const lines = Object.entries(contract).map(
    ([name, value]) => `export declare const ${name}: ${JSON.stringify(value)};`,
  );
  return ['// GENERATED by scripts/gen-desktop-contract.mjs — do not edit.', ...lines, ''].join(
    '\n',
  );
}

// ── CLI entry ────────────────────────────────────────────────────────────────────────────────────
if (import.meta.url === `file://${process.argv[1]}`) {
  const { writeFileSync } = await import('node:fs');
  const { join, dirname } = await import('node:path');
  const { fileURLToPath } = await import('node:url');

  const here = dirname(fileURLToPath(import.meta.url));
  const dist = join(here, '..', 'dist');
  const { DESKTOP_CONTRACT } = await import(join(dist, 'desktop-contract.js'));
  const outCjs = join(dist, 'desktop-contract.cjs');
  const outDts = join(dist, 'desktop-contract.d.cts');
  writeFileSync(outCjs, renderDesktopContract(DESKTOP_CONTRACT), 'utf8');
  writeFileSync(outDts, renderDesktopContractDts(DESKTOP_CONTRACT), 'utf8');
  process.stdout.write(
    `wrote desktop contract (${String(Object.keys(DESKTOP_CONTRACT).length)} constants) to dist/desktop-contract.{cjs,d.cts}\n`,
  );
}
